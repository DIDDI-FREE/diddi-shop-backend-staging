from typing import Protocol


class RewardsPort(Protocol):
    async def quote(self, customer_id: str, cart: dict, operation_id: str) -> dict: ...
    async def reserve(self, quote: dict, operation_id: str) -> dict: ...
    async def consume(self, reservation_id: str, order_id: str, operation_id: str) -> None: ...
    async def release(self, reservation_id: str, operation_id: str) -> None: ...
